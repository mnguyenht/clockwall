import { writeFile } from "node:fs/promises";
import countriesAndTimezones from "countries-and-timezones";

const timezones = Object.values(countriesAndTimezones.getAllTimezones({ deprecated: true }));
const timezoneByName = new Map(timezones.map((timezone) => [timezone.name, timezone]));
const countries = countriesAndTimezones.getAllCountries();

const canonicalZones = timezones.filter(
  (timezone) =>
    timezone.aliasOf === null && timezone.name.includes("/") && !timezone.name.startsWith("Etc/"),
);

// tzdata merged many capitals into one zone, but aliases with a different primary
// country retain the canonical city needed for search. Keeping all aliases would
// also duplicate old names such as Asia/Calcutta next to Asia/Kolkata.
const usefulAliases = timezones.filter((timezone) => {
  if (
    timezone.aliasOf === null ||
    timezone.countries.length === 0 ||
    !timezone.name.includes("/") ||
    timezone.name.startsWith("Etc/")
  ) {
    return false;
  }

  const parent = timezoneByName.get(timezone.aliasOf);
  return parent !== undefined && timezone.countries[0] !== parent.countries[0];
});

const aliasesByGroup = new Map();
for (const timezone of usefulAliases) {
  const key = `${timezone.aliasOf}|${timezone.countries[0]}`;
  const group = aliasesByGroup.get(key) ?? [];
  group.push(timezone);
  aliasesByGroup.set(key, group);
}

const dedupedAliases = [...aliasesByGroup.values()].map((group) =>
  group.sort((left, right) => left.name.localeCompare(right.name))[0],
);
const emittedZones = [...canonicalZones, ...dedupedAliases].sort((left, right) =>
  left.name.localeCompare(right.name),
);
const emittedZoneNames = new Set(emittedZones.map((timezone) => timezone.name));
const aliasesByZone = new Map();

for (const timezone of timezones) {
  if (!timezone.aliasOf || emittedZoneNames.has(timezone.name) || !emittedZoneNames.has(timezone.aliasOf)) {
    continue;
  }

  const alias = timezone.name.split("/").pop().replaceAll("_", " ").toLowerCase();
  const ownName = timezone.aliasOf.split("/").pop().replaceAll("_", " ").toLowerCase();
  if (alias === ownName) {
    continue;
  }

  const aliases = aliasesByZone.get(timezone.aliasOf) ?? new Set();
  aliases.add(alias);
  aliasesByZone.set(timezone.aliasOf, aliases);
}

const referencedCountryCodes = new Set(emittedZones.flatMap((timezone) => timezone.countries));
const countryLines = Object.entries(countries)
  .filter(([code]) => referencedCountryCodes.has(code))
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([code, country]) => `  ${code}: ${JSON.stringify(country.name)},`);
const zoneLines = emittedZones.map((timezone) => {
  const aliases = [...(aliasesByZone.get(timezone.name) ?? [])].sort().join(" ");
  return `  [${JSON.stringify(timezone.name)}, ${JSON.stringify(timezone.countries.join(" "))}, ${JSON.stringify(aliases)}],`;
});

const output = [
  "// GENERATED by scripts/generate-timezones.mjs - do not edit by hand.",
  "export const countryNames: Record<string, string> = {",
  ...countryLines,
  "};",
  "",
  "// [ianaZone, spaceSeparatedCountryCodes, spaceSeparatedAliasCityNames]",
  "export const zoneCountries: Array<[string, string, string]> = [",
  ...zoneLines,
  "];",
  "",
].join("\n");

await writeFile(new URL("../src/data/zoneCountries.generated.ts", import.meta.url), output, "utf8");
